import { test, expect } from "@playwright/test"
import { addWhiteMedium, applyCoupon } from "./support/shop"

test("TC-018: required address fields prevent empty checkout submission", async ({ page }) => {
  await addWhiteMedium(page)
  await page.getByRole("link", { name: "Go to checkout", exact: true }).click()
  const firstName = page.getByTestId("shipping-first-name-input")
  await expect(firstName).toBeVisible()
  await page.getByTestId("submit-address-button").click()
  await expect(page).toHaveURL(/step=address/)
  expect(await firstName.evaluate((input: HTMLInputElement) => input.validity.valueMissing)).toBe(true)
  await expect(firstName).toBeFocused()
  await expect(page.getByTestId("submit-delivery-option-button")).not.toBeVisible()
})

test("TC-019–021: local simulated checkout retains address and order confirmation", async ({ page }, testInfo) => {
  await addWhiteMedium(page)
  await applyCoupon(page)
  await page.getByRole("link", { name: "Go to checkout", exact: true }).click()
  await page.getByTestId("shipping-first-name-input").fill("QA")
  await page.getByTestId("shipping-last-name-input").fill("Playwright")
  await page.getByTestId("shipping-address-input").fill("1 Fictional QA Street")
  await page.getByTestId("shipping-postal-code-input").fill("2100")
  await page.getByTestId("shipping-city-input").fill("Copenhagen")
  await page.getByTestId("shipping-country-select").selectOption("dk")
  await page.getByTestId("shipping-email-input").fill(`qa-pw-${testInfo.project.name}-${Date.now()}@example.test`)
  await page.getByTestId("submit-address-button").click()
  await page.getByRole("radio", { name: "Standard Shipping €10.00", exact: true }).click()
  await expect(page.getByTestId("cart-shipping")).toHaveText("€10.00")
  await page.getByRole("button", { name: "Edit", exact: true }).click()
  await expect(page.getByTestId("shipping-address-input")).toHaveValue("1 Fictional QA Street")
  await page.getByTestId("submit-address-button").click()
  await page.getByTestId("submit-delivery-option-button").click()
  await page.getByRole("radio", { name: "Manual Payment Attention: For testing purposes only.", exact: true }).click()
  await page.getByTestId("submit-payment-button").click()
  await expect(page.getByTestId("cart-total")).toHaveText("€41.50")
  await page.getByTestId("submit-order-button").click()
  await expect(page).toHaveURL(/\/order\/order_[^/]+\/confirmed$/)
  const confirmationURL = page.url()
  await expect(page.getByTestId("order-complete-container")).toBeVisible()
  await expect(page.getByTestId("cart-total")).toHaveText("€41.50")
  await page.reload()
  await expect(page).toHaveURL(confirmationURL)
  await expect(page.getByTestId("cart-total")).toHaveText("€41.50")
  await testInfo.attach("order-confirmation", { body: await page.screenshot(), contentType: "image/png" })
  // This covers UI reload only; API repeat-completion remains manual coverage.
})
